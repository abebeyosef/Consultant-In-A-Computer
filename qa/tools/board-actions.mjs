import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3200";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(`${base}/board?fw=swot&fill=example`, { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
const count = () => p.evaluate(() => window.__ciacBoardApi.getSceneElements().filter((e) => e.customData?.role === "sticky").map((e) => e.customData.state).join(","));
console.log("initial", await count());
await p.getByRole("button", { name: "Clear AI items" }).click();
await p.waitForTimeout(300);
console.log("after clear", JSON.stringify(await count()), "bar text:", await p.locator("[data-testid=provisional-bar]").innerText().catch(() => "hidden"));
await p.getByRole("button", { name: /Re-fill/ }).click();
await p.waitForTimeout(800);
console.log("after refill", await count());
await p.keyboard.press("Meta+k");
await p.waitForTimeout(300);
console.log("cmd open", await p.getByPlaceholder("Open a framework…").isVisible());
await p.keyboard.type("five");
await p.keyboard.press("Enter");
await p.waitForTimeout(2000);
console.log("title now", await p.getByTestId("board-title").innerText(), p.url());
await p.screenshot({ path: "qa/screenshots/board-fivewhys.png" });
console.log("errors", errs);
await b.close();
