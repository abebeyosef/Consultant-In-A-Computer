// M8 screenshot pass: room hold / board / dim / captions, console room status.
import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3100";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light" });
const p = await ctx.newPage();
await p.goto(base + "/");
await p.getByLabel("Room mode").click();
await p.getByTestId("try-sample").click();
await p.waitForURL(/session/);
const [room] = await Promise.all([ctx.waitForEvent("page"), p.getByTestId("open-room").click()]);
await room.setViewportSize({ width: 1440, height: 810 });
await room.waitForTimeout(800);
await room.screenshot({ path: "qa/screenshots/m8-room-hold.png" });
await p.getByText("3×", { exact: true }).click();
await p.getByTestId("flag-card").first().waitFor({ timeout: 60000 });
await p.getByTestId("open-board").first().click();
await p.getByRole("button", { name: "Keep all" }).waitFor();
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Keep all" }).click();
await p.getByTestId("send-to-room").click();
await p.waitForTimeout(1500);
await p.screenshot({ path: "qa/screenshots/m8-console-in-room.png" });
await room.screenshot({ path: "qa/screenshots/m8-room-board.png" });
await p.keyboard.press("j");
await room.waitForTimeout(1500);
await room.screenshot({ path: "qa/screenshots/m8-room-captions.png" });
await room.keyboard.press("d");
await room.waitForTimeout(800);
await room.screenshot({ path: "qa/screenshots/m8-room-dim.png" });
await b.close();
console.log("done");
