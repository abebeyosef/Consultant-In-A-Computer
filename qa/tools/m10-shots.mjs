import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3100";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.grantPermissions(["clipboard-read", "clipboard-write"], { origin: base });
const p = await ctx.newPage();
await p.goto(base + "/board?fw=swot&fill=example");
await p.getByRole("button", { name: "Keep all" }).click({ timeout: 20000 });
await p.waitForTimeout(600);
await p.getByTestId("share-menu").click();
await p.waitForTimeout(300);
await p.screenshot({ path: "qa/screenshots/m10-share-menu.png" });
await p.getByTestId("copy-share-link").click();
const link = await p.evaluate(() => navigator.clipboard.readText());
console.log("link length", link.length);
const v = await ctx.newPage();
await v.goto(link);
await v.waitForTimeout(2000);
await v.screenshot({ path: "qa/screenshots/m10-view.png" });
await b.close();
