import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3200";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.screenshot({ path: "qa/screenshots/start-light.png" });
await p.getByTestId("try-sample").click();
await p.waitForURL(/\/session\//);
await p.waitForTimeout(1500);
console.log("interim visible early:", await p.getByTestId("interim").count());
await p.waitForTimeout(6000);
const words1 = (await p.getByTestId("transcript").innerText()).split(/\s+/).length;
console.log("words after ~7s:", words1);
// speed up
await p.getByRole("radio", { name: "3×" }).click().catch(() => p.getByText("3×").click());
await p.waitForTimeout(6000);
const words2 = (await p.getByTestId("transcript").innerText()).split(/\s+/).length;
console.log("words after 3x for 6s:", words2);
await p.screenshot({ path: "qa/screenshots/console-sample-light.png" });
await p.keyboard.press("m");
await p.waitForTimeout(300);
console.log("marked pins:", await p.getByLabel("Marked moment").count());
await p.keyboard.press("f");
await p.waitForTimeout(300);
console.log("focus mode:", await p.getByTestId("focus-mode").isVisible());
await p.screenshot({ path: "qa/screenshots/console-focus-light.png" });
await p.keyboard.press("f");
await p.getByTestId("pause").click();
await p.waitForTimeout(800);
await p.reload({ waitUntil: "networkidle" });
await p.waitForTimeout(1000);
const words3 = (await p.getByTestId("transcript").innerText()).split(/\s+/).length;
console.log("after reload words:", words3, "resume button:", await p.getByTestId("resume").isVisible());
await p.getByTestId("resume").click();
await p.waitForTimeout(2500);
const words4 = (await p.getByTestId("transcript").innerText()).split(/\s+/).length;
console.log("after resume words:", words4);
// paste path
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.getByTestId("paste-link").click();
await p.getByText("Use the sample transcript").click();
await p.getByText("Process instantly").click();
await p.getByTestId("paste-submit").click();
await p.waitForURL(/\/session\//);
await p.waitForTimeout(1500);
const words5 = (await p.getByTestId("transcript").innerText()).split(/\s+/).length;
console.log("paste instant words:", words5, "status ended:", await p.getByText("Session ended").isVisible());
console.log("errors", errs.slice(0, 5));
await b.close();
